export type KnownModelFamily =
  | "openai"
  | "anthropic"
  | "deepseek"
  | "gemini"
  | "meta"
  | "mistral"
  | "qwen"
  | "cohere"
  | "grok"
  | "ollama"
  | "openrouter"
  | "generic";

export type ModelInfo = {
  family: KnownModelFamily;
  displayName: string;
  rawModel: string;
};

/** Smart parser that detects model family and returns the exact model name for the badge */
export function resolveModelInfo(rawModel?: string | null): ModelInfo {
  if (!rawModel || !rawModel.trim()) {
    return { family: "generic", displayName: "AI Model", rawModel: "" };
  }

  const m = rawModel.trim();
  // Strip provider prefix if present (e.g. "openai/gpt-4o" -> "gpt-4o", "anthropic/claude-3.5-sonnet" -> "claude-3.5-sonnet")
  const stripped = m.includes("/") ? m.split("/").pop()! : m;
  const lower = stripped.toLowerCase();

  let family: KnownModelFamily = "generic";

  if (lower.includes("deepseek")) {
    family = "deepseek";
  } else if (lower.includes("claude") || lower.includes("anthropic")) {
    family = "anthropic";
  } else if (
    lower.startsWith("o1") || lower.startsWith("o3") ||
    lower.includes("gpt") || lower.includes("chatgpt") || lower.includes("openai")
  ) {
    family = "openai";
  } else if (lower.includes("gemini") || lower.includes("gemma")) {
    family = "gemini";
  } else if (lower.includes("llama") || lower.includes("meta")) {
    family = "meta";
  } else if (
    lower.includes("mistral") || lower.includes("mixtral") ||
    lower.includes("codestral") || lower.includes("ministral") || lower.includes("pixtral")
  ) {
    family = "mistral";
  } else if (lower.includes("qwen") || lower.includes("alibaba") || lower.includes("tongyi")) {
    family = "qwen";
  } else if (lower.includes("command") || lower.includes("cohere") || lower.includes("aya")) {
    family = "cohere";
  } else if (lower.includes("grok") || lower.includes("xai")) {
    family = "grok";
  } else if (lower.includes("ollama")) {
    family = "ollama";
  } else if (lower.includes("openrouter")) {
    family = "openrouter";
  }

  return {
    family,
    displayName: stripped,
    rawModel: m,
  };
}

