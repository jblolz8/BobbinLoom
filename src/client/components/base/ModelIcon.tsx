export function ModelBadge({ model, className = "" }: ModelBadgeProps) {
  if (!model) return null;
  const info = resolveModelInfo(model);

  return (
    <span
      className={`model-badge model-family-${info.family} ${className}`.trim()}
      title={`AI Model: ${info.rawModel}`}
    >
      <ModelIcon family={info.family} size={11} />
      <span className="model-badge-name">{info.displayName}</span>
    </span>
  );
}
